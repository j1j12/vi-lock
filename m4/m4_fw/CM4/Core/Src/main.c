static void MPU_ConfigSharedMemory(void)
{
  MPU_Region_InitTypeDef region = {0};

  HAL_MPU_Disable();
  region.Enable = MPU_REGION_ENABLE;
  region.Number = MPU_REGION_NUMBER0;
  region.BaseAddress = 0x10040000UL;
  region.Size = MPU_REGION_SIZE_64KB;
  region.SubRegionDisable = 0x00;
  /* TEX=1,C=0,B=0: Normal non-cacheable SRAM. TEX=0,C=0,B=0
   * selects Strongly-ordered memory, which forbids unaligned accesses. */
  region.TypeExtField = MPU_TEX_LEVEL1;
  region.AccessPermission = MPU_REGION_FULL_ACCESS;
  region.DisableExec = MPU_INSTRUCTION_ACCESS_DISABLE;
  region.IsShareable = MPU_ACCESS_SHAREABLE;
  region.IsCacheable = MPU_ACCESS_NOT_CACHEABLE;
  region.IsBufferable = MPU_ACCESS_NOT_BUFFERABLE;
  HAL_MPU_ConfigRegion(&region);
  HAL_MPU_Enable(MPU_PRIVILEGED_DEFAULT);
  __DSB();
  __ISB();
}

